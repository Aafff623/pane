let active: Locale = "en";
/// Filled from Rust `system_ui_locale` so Auto matches tray/toasts.
let systemLocale: Locale | null = null;

export function detectSystemLocale(): Locale {
  const lang = (navigator.language || "").toLowerCase();
  if (lang.startsWith("zh")) return "zh";
  if (lang.startsWith("ru")) return "ru";
  return "en";
}

export function setSystemLocale(locale: Locale): void {
  systemLocale = locale;
}

export function resolveLocale(pref: string | undefined): Locale {
  if (pref === "zh" || pref === "en" || pref === "ru") return pref;
  return systemLocale ?? detectSystemLocale();
}

export function normalizeLocalePref(raw: unknown): LocalePref {
  return raw === "en" || raw === "zh" || raw === "ru" || raw === "auto" ? raw : "auto";
}

export function setActiveLocale(locale: Locale): void {
  active = locale;
}

export function getLocale(): Locale {
  return active;
}

export function localeTag(): string {
  if (active === "zh") return "zh-CN";
  if (active === "ru") return "ru-RU";
  return "en-US";
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const dict = active === "zh" ? zh : active === "ru" ? ru : en;
  let s = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

export function displayMetricLabel(label: string): string {
  const key = METRIC_KEYS[label];
  if (key) return t(key);
  // Per-currency balances (DeepSeek: "Balance (CNY)") keep the currency and
  // localize only the noun.
  const balance = label.match(/^Balance \(([A-Z]{3})\)$/);
  if (balance) return `${t("metric.balance")} (${balance[1]})`;
  const resetCredit = label.match(/^Reset credit(?: (\d+))?$/);
  if (resetCredit) {
    return resetCredit[1]
      ? t("metric.resetCreditNumbered", { n: resetCredit[1] })
      : t("metric.resetCredit");
  }
  if (label.endsWith(" weekly")) {
    return t("metric.modelWeekly", { model: label.slice(0, -7) });
  }
  // GIPHY's per-app rows are labelled with the app name (a vendor string,
  // left as-is); its weekly-total row appends a fixed suffix that would
  // otherwise stay English forever.
  const appDays = label.match(/^(.+) · last (\d+) days$/);
  if (appDays) return t("metric.appLastNDays", { app: appDays[1], n: appDays[2] });
  return label;
}

/// Rust emits card hints in English (per-provider no-data / degraded
/// messages). Translate the known shapes at paint time so a Chinese or
/// Russian UI never shows a bare English sentence where the guidance
/// lives.
export function displayCardHint(text: string): string {
  if (getLocale() === "en" || !text) return text;
  // Match the backend's complete, fixed English messages. Unknown hints
  // remain intact, and the local HTTP API keeps its existing message contract.
  const stepPlanKey = ["card.stepPlanRejected", "card.stepPlanPair", "card.stepPlanApiKey", "card.stepPlanEmpty"]
    .find((key) => en[key] === text);
  if (stepPlanKey) return t(stepPlanKey);
  const generic = text.match(/^Sign in with (.+) from the auth center to see its quota\.$/);
  if (generic) return t("card.hintSignIn", { name: generic[1] });
  if (
    /^WorkBuddy's desktop sign-in is stored encrypted on this machine and Pane does not decrypt it\. Sign in from the auth center instead\.$/.test(
      text,
    )
  ) {
    return t("card.hintWorkbuddyEncrypted");
  }
  const unreadable = text.match(/^WorkBuddy desktop sign-in could not be read: (.+)$/);
  if (unreadable) return t("card.hintWorkbuddyUnreadable", { reason: unreadable[1] });
  const expired = text.match(/^(.+) session expired — sign in again from the auth center$/);
  if (expired) return t("card.hintSessionExpired", { name: expired[1] });
  if (/^WorkBuddy web session expired — import a fresh cookie in Customize, or sign in from the auth center\.$/.test(text)) {
    return t("card.hintWbWebExpired");
  }
  const webErr = text.match(/^WorkBuddy web session: (.+)$/);
  if (webErr) return t("card.hintWbWebError", { reason: webErr[1] });
  if (/^WorkBuddy web session returned no quota data$/.test(text)) {
    return t("card.hintWbWebNoData");
  }
  return text;
}

export function displayLinkLabel(label: string): string {
  const key = `link.${label}`;
  const translated = t(key);
  return translated === key ? label : translated;
}

/// Rust still emits English captions ("$21.80 of $79.56 left · 545 credits").
/// Translate the known shapes at paint time so layout keys stay English.
export function displayMetricDetail(text: string): string {
  if (getLocale() === "en" || !text) return text;
  const money = "\\$[\\d,]+(?:\\.\\d+)?K?";
  const num = "[\\d,]+(?:\\.\\d+)?";
  let m = text.match(new RegExp(`^(${money}) of (${money}) left(?: · (\\d+) credits)?$`, "i"));
  if (m) {
    return m[3]
      ? t("detail.moneyOfLeftCredits", { a: m[1], b: m[2], n: m[3] })
      : t("detail.moneyOfLeft", { a: m[1], b: m[2] });
  }
  m = text.match(new RegExp(`^(${money}) left of (${money})$`, "i"));
  if (m) return t("detail.moneyLeftOf", { a: m[1], b: m[2] });
  m = text.match(new RegExp(`^(${money}) of (${money}) used$`, "i"));
  if (m) return t("detail.moneyOfUsed", { a: m[1], b: m[2] });
  m = text.match(new RegExp(`^(${money}) of (${money}) limit$`, "i"));
  if (m) return t("detail.moneyOfLimit", { a: m[1], b: m[2] });
  m = text.match(new RegExp(`^(${money}) of (${money})$`, "i"));
  if (m) return t("detail.moneyOf", { a: m[1], b: m[2] });
  m = text.match(new RegExp(`^(${money}) · (\\d+) credits$`, "i"));
  if (m) return t("detail.moneyCredits", { a: m[1], n: m[2] });
  m = text.match(new RegExp(`^(${num}) of (${num}) credits used$`, "i"));
  if (m) return t("detail.countCreditsUsed", { a: m[1], b: m[2] });
  m = text.match(new RegExp(`^(${num}) of (${num}) used$`, "i"));
  if (m) return t("detail.countOfUsed", { a: m[1], b: m[2] });
  m = text.match(new RegExp(`^(${num}) of (${num}) left$`, "i"));
  if (m) return t("detail.countOfLeft", { a: m[1], b: m[2] });
  if (/^available$/i.test(text.trim())) return t("card.available");
  if (/^weekend not started$/i.test(text.trim())) return t("detail.weekendNotStarted");
  if (/^unlimited$/i.test(text.trim())) return t("detail.unlimited");
  // GIPHY. The bar's denominator comes from GIPHY's *documented* 100/hour
  // beta cap, not from any readable quota, and the numerator is the newest
  // completed day — the translation must keep saying both.
  m = text.match(
    /^([\d,]+) of ([\d,]+) calls · last completed day (\d{4}-\d{2}-\d{2}) · ceiling derived from ([\d,]+) calls\/hour × 24$/,
  );
  if (m) return t("detail.ceilingOfCalls", { n: m[1], c: m[2], d: m[3], r: m[4] });
  m = text.match(/^([\d,]+) calls · last completed day (\d{4}-\d{2}-\d{2})$/);
  if (m) return t("detail.completedDayCalls", { n: m[1], d: m[2] });
  m = text.match(/^([\d,]+) calls$/);
  if (m) return t("detail.calls", { n: m[1] });
  if (/^no completed day yet$/i.test(text.trim())) return t("detail.noCompletedDay");
  return text;
}

export function applyStaticI18n(): void {
  document.documentElement.lang = localeTag();
  document.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-html]").forEach((el) => {
    const key = el.dataset.i18nHtml;
    if (key) el.innerHTML = t(key);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (key) {
      el.title = t(key);
      delete el.dataset.tip;
    }
  });
  // Self-drawn hover tips (the panel rail) read dataset.tip in CSS; the same
  // label is the accessible name for the icon-only buttons.
  document.querySelectorAll<HTMLElement>("[data-i18n-tip]").forEach((el) => {
    const key = el.dataset.i18nTip;
    if (!key) return;
    const label = t(key);
    el.dataset.tip = label;
    el.setAttribute("aria-label", label);
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-placeholder]").forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (key && "placeholder" in el) {
      (el as HTMLInputElement).placeholder = t(key);
    }
  });
  document.querySelectorAll<HTMLElement>("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria;
    if (key) el.setAttribute("aria-label", t(key));
  });
}
